import pytest
from services.nextday import next_day


# ---------- Некорректные типы ----------
@pytest.mark.parametrize("d,m,y", [
    ("15", 3, 2023),
    (15, "3", 2023),
    (15, 3, "2023"),
])
def test_wrong_type(d, m, y):
    assert next_day(d, m, y) is None


# ---------- Некорректные значения ----------
@pytest.mark.parametrize("d,m,y", [
    (0, 3, 2023),      # day < 1
    (-1, 3, 2023),     # day < 1
    (15, 0, 2023),     # month < 1
    (15, 13, 2023),    # month > 12
    (15, 3, 0),        # year < 1
    (15, 3, -1),       # year < 1
    (31, 4, 2023),     # 31 апреля — не существует
    (29, 2, 2023),     # 29 февраля в невисокосный год
    (30, 2, 2024),     # 30 февраля — не существует даже в високосный
])
def test_invalid_values(d, m, y):
    assert next_day(d, m, y) is None


# ---------- Обычный день (не последний в месяце) ----------
def test_middle_of_month():
    assert next_day(15, 3, 2023) == (16, 3, 2023)


# ---------- Последний день месяца (30/31) ----------
@pytest.mark.parametrize("d,m,y,exp", [
    (30, 4, 2023, (1, 5, 2023)),   # 30-дневный месяц
    (31, 3, 2023, (1, 4, 2023)),   # 31-дневный месяц
    (31, 1, 2023, (1, 2, 2023)),
    (30, 6, 2023, (1, 7, 2023)),
])
def test_last_day_of_month(d, m, y, exp):
    assert next_day(d, m, y) == exp


# ---------- Февраль: обычный / високосный ----------
@pytest.mark.parametrize("d,m,y,exp", [
    (28, 2, 2023, (1, 3, 2023)),   # обычный год
    (28, 2, 1900, (1, 3, 1900)),   # 1900 — не високосный (÷100, не ÷400)
    (29, 2, 2024, (1, 3, 2024)),   # 2024 — високосный (÷4)
    (29, 2, 2000, (1, 3, 2000)),   # 2000 — високосный (÷400)
])
def test_february(d, m, y, exp):
    assert next_day(d, m, y) == exp


# ---------- 29 февраля в невисокосный год — ошибка ----------
def test_feb29_not_leap():
    assert next_day(29, 2, 2023) is None


# ---------- 28 февраля в невисокосном году ----------
def test_feb28_not_leap():
    assert next_day(28, 2, 2023) == (1, 3, 2023)


# ---------- Конец года ----------
def test_end_of_year():
    assert next_day(31, 12, 2023) == (1, 1, 2024)


# ---------- 31 декабря високосного года ----------
def test_end_of_leap_year():
    assert next_day(31, 12, 2024) == (1, 1, 2025)


# ---------- Дополнительно: месяц из 30 дней, конец ----------
def test_april_end():
    assert next_day(30, 4, 2024) == (1, 5, 2024)