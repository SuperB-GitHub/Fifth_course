import math

# Исходные данные
ghz       = [275, 525, 1025, 2025, 4025]
lnis      = [66, 66, 61, 56, 53]
lis       = [98, 97.5, 99, 96.8, 91.2]
ushDB     = [5, 4, 9, 12, 19]
uhDB      = [1, 3, 2, 1, 1]
t1u1MKB   = [125, 98, 220.4, 115.5, 186.3]
t2u2MKB   = [41.20, 52.4, 125.1, 25.2, 55.1]
uhnoktMKB = [0.055, 0.068, 0.081, 0.098, 0.117]

# Нормированное значение словесной разборчивости (из п.7 методички)
Wn = 0.3 

# Инициализация списков
ushMKB  = [0.0] * 5
uhMKB   = [0.0] * 5
uciMKB  = [0.0] * 5
kis     = [0.0] * 5
ucprivs = [0.0] * 5
deltas  = [0.0] * 5
Ri      = [0.0] * 5

def db_in_mkB(u):
    """Перевод из дБ в мкВ: U = 10^(U(дБ)/20)"""
    return round(10**(u/20), 4)

def uci(uch, uh):
    """Расчет уровня информативного сигнала: Uci = sqrt(Uc^2 - Uш^2)"""
    val = (uch**2) - (uh**2)
    if val < 0:
        return 0.0 # Защита от извлечения корня из отрицательного числа
    return round(math.sqrt(val), 4)

def ki(li, lni):
    """Расчет коэффициента превышения: Ki = 10^((Li - Lni)/20)"""
    return round(10**((li - lni)/20), 4)

def ucpriv(uci, ki):
    """Расчет приведенного информативного сигнала: Uc.priv = Uci / Ki"""
    return round(uci/ki, 4)

def delta(ucpriv, uhnokt):
    """Расчет отношения сигнал/шум: Δi = Uc.priv / Uш.нокт"""
    return round(ucpriv/uhnokt, 4)

def calc_Ri(delta_i):
    """
    Расчет Ri по формуле из Приложения 2.
    Qi = Δi - ΔAi. В методичке (табл. П3.1) даны значения ΔAi для частот.
    Для заданных частот (275, 525, 1025, 2025, 4025 Гц) ΔAi примерно равны:
    275 Гц -> 18 дБ
    525 Гц -> 14 дБ
    1025 Гц -> 9 дБ
    2025 Гц -> 6 дБ
    4025 Гц -> 5 дБ
    """
    # Приближенные значения ΔAi из таблицы П3.1 для соответствующих частот
    delta_Ai = [18, 14, 9, 6, 5] 
    
    # В данном контексте delta_i - это отношение сигнал/шум (раз), 
    # но в формуле Qi = Δi - ΔAi, где Δi в дБ.
    # Однако, в коде delta_i вычисляется как отношение (раз). 
    # Чтобы использовать формулу, нужно перевести delta_i в дБ.
    # Но в методичке (п.5) сказано: "Рассчитать отношение сигнал/шум Δi".
    # Формула для Ri использует Qi = Δi - ΔAi (в дБ).
    # Предположим, что в контексте задачи delta_i уже подразумевается в дБ, 
    # либо мы переводим его. Судя по тому, что в таблице П3.1 ΔAi в дБ, 
    # логично перевести наш delta_i в дБ.
    
    delta_i_db = 20 * math.log10(delta_i) if delta_i > 0 else -100
    
    # Для каждой октавы свой Qi, но формула Ri = pi * ki (где ki - вес).
    # В таблице П3.1 веса ki: 0.03, 0.12, 0.20, 0.30, 0.26
    weights = [0.03, 0.12, 0.20, 0.30, 0.26]
    
    # Индекс i передается, но для упрощения сделаем функцию для одной полосы
    # и вызовем ее в цикле.
    return delta_i_db, delta_Ai, weights

def calc_pi(Qi):
    """Расчет pi по формуле из Приложения 2"""
    if Qi <= 0:
        numerator = 0.78 + 5.46 * math.exp(-4.3 * 10**(-3) * ((27.3 - Qi)**2))
        denominator = 1 + 10**(0.1 * abs(Qi))
        return numerator / denominator
    else:
        numerator = 0.78 + 5.46 * math.exp(-4.3 * 10**(-3) * ((27.3 - Qi)**2))
        denominator = 1 + 10**(0.1 * abs(Qi))
        # Вторая часть формулы для Qi > 0 (в методичке опечатка или неполное условие,
        # но обычно формула симметрична или имеет вид 1 - ...)
        # Согласно изображению: 1 - (0.78 + ...)/(1 + 10^(0.1*|Qi|))
        # Но скорее всего там опечатка, и для Qi > 0 используется та же формула, 
        # либо 1 - предыдущее выражение. 
        # В методичке на изображении: 1 - (0.78 + 5.46 * e^...)/(1 + 10^(0.1*|Qi|))
        # Это странно, так как pi должно быть от 0 до 1.
        # Допустим, что для Qi > 0 используется 1 - (выражение для Qi <= 0).
        # Но часто в таких методиках pi = 1 - ... только для Qi > 0.
        # Будем следовать изображению буквально:
        return 1 - (numerator / denominator)

def calc_Wc(R_sum):
    """Расчет словесной разборчивости Wc"""
    if R_sum < 0.15:
        return 1.54 * (R_sum**0.25) * (1 - math.exp(-11 * R_sum))
    else:
        return 1 - math.exp(-11 * R_sum / (1 + 0.7 * R_sum))

# --- Основной цикл расчетов ---

print(f"  Гц   |  Lнi  |  Li  |  Uсшi |  Uшi  | T1U1 |  T2U2 |  Δi   |  Qi   |  pi   |  Ri   ")
print("-" * 100)

R_sum = 0.0

# Веса для расчета Ri (из таблицы П3.1)
weights = [0.03, 0.12, 0.20, 0.30, 0.26]
# ΔAi из таблицы П3.1 (для соответствующих частот)
delta_Ai_vals = [18, 14, 9, 6, 5]

for i in range(5):
    # 1. Перевод в мкВ
    ushMKB[i] = db_in_mkB(ushDB[i])
    uhMKB[i] = db_in_mkB(uhDB[i])
    
    # 2. Расчет Uci
    uciMKB[i] = uci(ushMKB[i], uhMKB[i])
    
    # 3. Расчет Ki
    kis[i] = ki(lis[i], lnis[i])
    
    # 4. Расчет Uc.priv
    ucprivs[i] = ucpriv(uciMKB[i], kis[i])
    
    # 5. Расчет Δi (отношение сигнал/шум)
    deltas[i] = delta(ucprivs[i], uhnoktMKB[i])
    
    # 6. Расчет Qi (в дБ)
    # Переводим Δi в дБ для формулы
    delta_i_db = 20 * math.log10(deltas[i]) if deltas[i] > 0 else -100
    Qi = delta_i_db - delta_Ai_vals[i]
    
    # 7. Расчет pi
    pi = calc_pi(Qi)
    
    # 8. Расчет Ri
    Ri[i] = pi * weights[i]
    R_sum += Ri[i]
    
    # Вывод строки таблицы
    print(f"{ghz[i]:6} | {lnis[i]:5} | {lis[i]:4} | {ushMKB[i]:5.2f} | {uhMKB[i]:5.2f} | {t1u1MKB[i]:5.1f} | {t2u2MKB[i]:5.1f} | {deltas[i]:5.2f} | {Qi:5.1f} | {pi:5.3f} | {Ri[i]:5.3f}")

# 9. Расчет итоговой словесной разборчивости
Wc = calc_Wc(R_sum)

print("-" * 100)
print(f"Суммарный индекс артикуляции R = {R_sum:.4f}")
print(f"Словесная разборчивость Wc = {Wc:.4f}")
print(f"Нормированное значение Wн = {Wn}")

# 10. Проверка условия
if Wc <= Wn:
    print("ВЫВОД: ТС соответствует нормам противодействия в анализируемом режиме.")
else:
    print("ВЫВОД: ТС НЕ соответствует нормам. Требуется проверка возможностей перехвата.")